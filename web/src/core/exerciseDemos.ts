const key = (s: string) => s.toLowerCase().replace(/[’']/g, "'").trim();
const BY_KEY = new Map(Object.entries(DEMO_IDS).map(([k, v]) => [key(k), v]));

/** The photo set for an exercise name, also trying it without a "(…)" note or a ": …" suffix ("Bench: 2 ramp-up sets"). */
export function demoId(name: string): string | null {
  const base = name.split(':')[0];
  return BY_KEY.get(key(name)) ?? BY_KEY.get(key(base)) ?? BY_KEY.get(key(base.replace(/\s*\(.*?\)\s*/g, ' '))) ?? null;
}
